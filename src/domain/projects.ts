import type { DeadProject, ProjectCategory, ProjectRecord, ProjectStatus } from './types';

interface Extra {
  targetOs?: string;
  release?: string;
  license?: string;
  codeOpen?: ProjectRecord['codeOpen'];
  reproducibility?: ProjectRecord['reproducibility'];
  evidence?: string[];
}

const CATEGORY_EVIDENCE: Record<ProjectCategory, string[]> = {
  bootloader: ['E-OC-108'],
  kext: ['E-OC-108'],
  gpu: ['E-DORTANIA-GPU-AMD'],
  wireless: ['E-ITLWM'],
  peripheral: ['E-APPLEIGC'],
  toolchain: ['E-OC-SIMPLIFY'],
  amd: ['E-AMD-VANILLA'],
  arm: ['E-UNIXNU'],
  community: ['E-DALIANSKY'],
  virtualization: ['E-OSXKVM'],
};

let seq = 0;
function p(
  name: string,
  repo: string,
  stars: number,
  pushedAt: string,
  status: ProjectStatus,
  category: ProjectCategory,
  description: string,
  year: number,
  extra: Extra = {},
): ProjectRecord {
  seq += 1;
  const id = `p-${String(seq).padStart(3, '0')}`;
  return {
    id,
    name,
    repo,
    url: `https://github.com/${repo}`,
    category,
    description,
    stars,
    pushedAt,
    status,
    codeOpen: extra.codeOpen ?? 'full',
    reproducibility: extra.reproducibility ?? 'verified',
    createdYear: year,
    evidenceIds: extra.evidence ?? CATEGORY_EVIDENCE[category],
    ...(extra.targetOs ? { targetOs: extra.targetOs } : {}),
    ...(extra.release ? { latestRelease: extra.release } : {}),
    ...(extra.license ? { license: extra.license } : {}),
  };
}

