const INDEX = new Map(EVIDENCE.map((e) => [e.id, e]));

export function getEvidence(id: string): Evidence {
  const found = INDEX.get(id);
  if (!found) throw new Error(`未知证据 ID: ${id}`);
  return found;
}

export function getEvidenceList(ids: readonly string[]): Evidence[] {
  return ids.map(getEvidence);
}

export const EVIDENCE_GRADE_LABEL: Record<Evidence['grade'], string> = {
  official: '官方文档',
  upstream: '上游代码',
  reproducible: '可复现测试',
  community: '社区报告',
  'vendor-claim': '项目方声明',
  inference: '推断',
};

/** 强弱排序，用于「最强证据」展示 */
export const EVIDENCE_RANK: Record<Evidence['grade'], number> = {
  official: 5,
  upstream: 4,
  reproducible: 3,
  community: 2,
  'vendor-claim': 1,
  inference: 0,
};

export function strongestGrade(ids: readonly string[]): Evidence['grade'] {
  let best: Evidence['grade'] = 'inference';
  for (const id of ids) {
    const g = getEvidence(id).grade;
    if (EVIDENCE_RANK[g] > EVIDENCE_RANK[best]) best = g;
  }
  return best;
}
